import { BaremTable, BaremCell, TableColumn } from './types';

/**
 * Helper para construir celdas del baremo de forma legible.
 * - `v(n)`: valor único, por ejemplo "5" → { min: 5, max: 5 }
 * - `r(a, b)`: rango inclusivo, por ejemplo "16-17" → { min: 16, max: 17 }
 * - `x()`: celda vacía "--" → { min: null, max: null }
 */
const v = (n: number): BaremCell => ({ min: n, max: n });
const r = (a: number, b: number): BaremCell => ({ min: a, max: b });
const x = (): BaremCell => ({ min: null, max: null });

/**
 * Helper para construir una fila del baremo.
 * Orden de columnas: V7-8, V9-10, V11-15, M7-8, M9-10, M11-15
 */
function row(
  pc: number,
  z: number,
  t: number,
  v78: BaremCell,
  v910: BaremCell,
  v1115: BaremCell,
  m78: BaremCell,
  m910: BaremCell,
  m1115: BaremCell,
) {
  const cells: Record<TableColumn, BaremCell> = {
    'V7-8': v78,
    'V9-10': v910,
    'V11-15': v1115,
    'M7-8': m78,
    'M9-10': m910,
    'M11-15': m1115,
  };
  return { pc, z, t, cells };
}

